def generate_attack_library():
    """生成完整的 50 类攻击库，每类 20 个探针"""
    # 生成每个类别的探针
    library = {}
    total = 0
    for cat, template_funcs in TEMPLATES.items():
        probes = []
        for idx, func in enumerate(template_funcs[:20]):  # 只取前 20 个
            try:
                template = func(idx)
                probes.append({"id": f"{cat[:3]}{idx:02d}", "turns": [template]})
            except Exception as e:
                print(f"Error in {cat}[{idx}]: {e}")
                continue
        if probes:  # 只添加非空类别
            library[cat] = probes
            total += len(probes)
    
    print(f"Generated {len(library)} categories with {total} probes")
    return library

